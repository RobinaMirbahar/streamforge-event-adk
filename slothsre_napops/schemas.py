from typing import List, Literal
from pydantic import BaseModel, Field


class RawOvernightEvent(BaseModel):
    """A single noisy alert, CI failure, or chat message captured while the engineer sleeps."""

    event_id: str = Field(..., description="Unique alert or webhook identifier.")
    timestamp_utc: str = Field(..., description="ISO-8601 UTC timestamp of the alert.")
    source: Literal["github_actions", "cloud_run_logs", "oncall_chat", "dependabot"] = Field(
        ..., description="Originating system."
    )
    severity: Literal["ERROR", "WARNING", "INFO"] = Field(default="ERROR")
    service_name: str = Field(..., description="Target microservice or repository.")
    log_lines_count: int = Field(..., ge=1, description="Number of raw stack-trace or log lines.")
    raw_payload: str = Field(..., description="Raw stack trace, CI log, or chat transcript.")


class VerifiedPatchArtifact(BaseModel):
    """Minimal git patch verified in a local sandbox before the engineer wakes up."""

    cluster_id: str = Field(..., description="Deduplicated incident cluster identifier.")
    target_file: str = Field(..., description="Repository file patched by Gemma 4.")
    git_diff_patch: str = Field(..., description="Unified git diff ready for 1-click apply.")
    sandbox_pytest_passed: bool = Field(
        ..., description="True if local pytest suite passed with the patch applied."
    )
    test_duration_ms: float = Field(..., description="Execution time of sandbox verification.")


class TwoLineIncidentDigest(BaseModel):
    """Strict 2-line morning summary enforcing the 'Slow and Steady' anti-burnout contract."""

    cluster_id: str = Field(..., description="Deduplicated incident cluster ID.")
    service_name: str = Field(..., description="Impacted microservice.")
    raw_events_collapsed: int = Field(
        ..., description="Number of duplicate raw overnight alerts merged into this digest."
    )
    raw_lines_collapsed: int = Field(
        ..., description="Number of raw stack-trace lines compressed into 2 lines."
    )
    line_1_what_broke: str = Field(
        ..., description="Line 1: Plain-English root cause in a single sentence."
    )
    line_2_verified_fix: str = Field(
        ..., description="Line 2: Exact verified fix and test result in a single sentence."
    )
    one_click_command: str = Field(
        ..., description="Single CLI or git command to apply/merge the verified fix."
    )
    patch: VerifiedPatchArtifact = Field(..., description="Attached sandbox-verified patch.")


class SentryAgentSpanRecord(BaseModel):
    """Captured Sentry Agent Tracing (gen_ai.*) telemetry span."""

    span_id: str
    op: str = Field(..., description="Sentry operation name, e.g., gen_ai.agent or gen_ai.tool.")
    description: str
    model_id: str = Field(default="ollama/gemma4:27b")
    input_tokens: int
    output_tokens: int
    duration_ms: float
    status: str = Field(default="ok")


class SlothMorningReport(BaseModel):
    """Complete 8:00 AM NapOps report generated by open-weights Gemma 4."""

    report_id: str = Field(default="SLOTH-2026-10-20-AM")
    generated_by_model: str = Field(default="google/gemma-4-27b-it (local Ollama / vLLM)")
    total_raw_events: int = Field(..., description="Total noisy alerts received overnight.")
    total_raw_log_lines: int = Field(..., description="Total lines of stack traces and chat logs.")
    unique_actionable_clusters: int = Field(
        ..., description="Deduplicated actionable incidents after Gemma 4 clustering."
    )
    noise_reduction_pct: float = Field(
        ..., description="Percentage of raw log lines eliminated before morning review."
    )
    estimated_minutes_saved: int = Field(
        ..., description="Estimated manual triage minutes saved for the sleeping engineer."
    )
    sentry_trace_id: str = Field(..., description="Root Sentry Agent Tracing transaction ID.")
    sentry_spans: List[SentryAgentSpanRecord] = Field(
        ..., description="Recorded Sentry gen_ai.* agent and tool spans."
    )
    digests: List[TwoLineIncidentDigest] = Field(
        ..., description="List of 2-line incident digests ready for 1-click approval."
    )
